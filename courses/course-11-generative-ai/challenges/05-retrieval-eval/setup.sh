"""
Eval harness — do not edit this file.

Provides compute_recall_at_k() for the verifier and a __main__ runner
so you can check your progress locally.
"""

import json
import os


def load_fixtures():
    base = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(base, "corpus_embs.json")) as f:
        corpus_embs = json.load(f)
    with open(os.path.join(base, "eval_set.json")) as f:
        eval_set = json.load(f)
    return corpus_embs, eval_set


def compute_recall_at_k(retrieve_fn, corpus_embs, eval_set, k):
    """Return recall@k in [0, 1] for the given retrieve function."""
    hits = 0
    for item in eval_set:
        result = retrieve_fn(item["query_emb"], corpus_embs, k)
        if any(rel_id in result for rel_id in item["relevant_ids"]):
            hits += 1
    return hits / len(eval_set)


if __name__ == "__main__":
    from retriever import retrieve as retrieve_fn

    corpus_embs, eval_set = load_fixtures()
    for k in [1, 3, 5]:
        r = compute_recall_at_k(retrieve_fn, corpus_embs, eval_set, k)
        print(f"recall@{k} = {r:.2f}  ({int(r * len(eval_set))}/{len(eval_set)})")
PYEOF

