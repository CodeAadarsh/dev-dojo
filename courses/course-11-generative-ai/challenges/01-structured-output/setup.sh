"""
Structured Output — parse and validate LLM-generated JSON into a fixed schema.

Schema:
    {
        "title":             str  (non-empty),
        "severity":          str  ("low" | "medium" | "high" | "critical"),
        "affected_services": list[str]  (CSV string is coerced to list),
        "resolution_steps":  list[str]  (non-empty)
    }

Rules:
  - Strip keys not in the schema from the parsed dict.
  - Lowercase severity; raise ValueError if not in VALID_SEVERITIES.
  - If affected_services is a comma-separated string, split and strip each element.
  - Raise ValueError for any other constraint violation.
"""

import json

SCHEMA_KEYS = {"title", "severity", "affected_services", "resolution_steps"}
VALID_SEVERITIES = {"low", "medium", "high", "critical"}


