cat > "$WORK/test_solution.py" << 'PYEOF'
"""Pytest harness — do not edit this file."""
import json
import pytest
from solution import parse_incident_report, SCHEMA_KEYS, VALID_SEVERITIES


def assert_schema(result: dict) -> None:
    assert isinstance(result, dict), "return value must be a dict"
    assert set(result.keys()) == SCHEMA_KEYS, (
        f"dict must have exactly {SCHEMA_KEYS}, got {set(result.keys())}"
    )
    assert isinstance(result["title"], str) and result["title"], \
        "title must be a non-empty str"
    assert result["severity"] in VALID_SEVERITIES, (
        f"severity must be one of {VALID_SEVERITIES}, got {result['severity']!r}"
    )
    assert isinstance(result["affected_services"], list), \
        "affected_services must be a list"
    assert isinstance(result["resolution_steps"], list) and result["resolution_steps"], \
        "resolution_steps must be a non-empty list"


def test_clean_valid_json():
    raw = json.dumps({
        "title": "DB Connection Pool Exhausted",
        "severity": "high",
        "affected_services": ["auth-service", "billing"],
        "resolution_steps": ["Scale connection pool to 100", "Add request queuing"],
    })
    result = parse_incident_report(raw)
    assert_schema(result)
    assert result["title"] == "DB Connection Pool Exhausted"
    assert result["severity"] == "high"
    assert result["affected_services"] == ["auth-service", "billing"]


def test_extra_keys_are_stripped():
    raw = json.dumps({
        "title": "Cache Miss Storm",
        "severity": "medium",
        "affected_services": ["cache", "api-gateway"],
        "resolution_steps": ["Enable cache warming"],
        "root_cause": "cold start after deploy",
        "timestamp": "2026-10-31T09:15:00Z",
    })
    result = parse_incident_report(raw)
    assert_schema(result)
    assert set(result.keys()) == SCHEMA_KEYS, "extra keys must be stripped"


def test_severity_uppercase_is_normalised():
    raw = json.dumps({
        "title": "Disk Full on Metrics Node",
        "severity": "CRITICAL",
        "affected_services": ["metrics-agent", "prometheus"],
        "resolution_steps": ["Clear old logs", "Add disk capacity alert"],
    })
    result = parse_incident_report(raw)
    assert_schema(result)
    assert result["severity"] == "critical", "severity must be lowercased"


def test_affected_services_csv_string_is_split():
    raw = json.dumps({
        "title": "Cert Expiry",
        "severity": "high",
        "affected_services": "ingress-nginx, cert-manager, api",
        "resolution_steps": ["Renew certificate", "Automate with cert-manager"],
    })
    result = parse_incident_report(raw)
    assert_schema(result)
    assert isinstance(result["affected_services"], list), \
        "CSV string must be split into a list"
    assert len(result["affected_services"]) == 3, \
        "expected 3 services after splitting 'ingress-nginx, cert-manager, api'"
    assert all(s == s.strip() for s in result["affected_services"]), \
        "each service name must have surrounding whitespace stripped"


def test_invalid_severity_raises_value_error():
    raw = json.dumps({
        "title": "Some Incident",
        "severity": "urgent",
        "affected_services": ["api"],
        "resolution_steps": ["Fix it"],
    })
    with pytest.raises(ValueError):
        parse_incident_report(raw)
PYEOF

