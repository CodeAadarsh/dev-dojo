    """
    Parse a raw JSON string (LLM output) into a validated incident report dict.

    Args:
        raw: JSON string, possibly with extra keys or minor type mismatches.

    Returns:
        A dict with exactly the four schema keys, passing all schema constraints.

    Raises:
        ValueError: if a schema constraint cannot be satisfied.
        json.JSONDecodeError: if raw is not valid JSON.
    """
